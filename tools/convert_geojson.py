"""
convert_geojson.py
------------------
Converts tools/india_districts.geojson (760 district polygons, Census 2011 boundaries
re-cut for the current 36 states / UTs) into the two artefacts the application needs:

  1. opengl/data/india.map      - compact text geometry file read by frontend/opengl/Map/IndiaMap.cpp
  2. database/seed_geo.sql      - INSERTs for states, districts and cities (one district HQ city per district)

State borders are not present in the source file, so they are derived here:
an edge that belongs to exactly one district, or to two districts of DIFFERENT states,
lies on a state boundary. Those segments are chained into polylines.

Run:  python tools/convert_geojson.py
"""
import json
import math
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "india_districts.geojson")
MAP_OUT = os.path.join(ROOT, "opengl", "data", "india.map")
SQL_OUT = os.path.join(ROOT, "database", "seed_geo.sql")

Q = 5  # decimal places used to match shared vertices


def q(p):
    return (round(p[0], Q), round(p[1], Q))


def ring_area_centroid(ring):
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        c = x1 * y2 - x2 * y1
        a += c
        cx += (x1 + x2) * c
        cy += (y1 + y2) * c
    if abs(a) < 1e-12:
        xs = [p[0] for p in ring]
        ys = [p[1] for p in ring]
        return 0.0, sum(xs) / len(xs), sum(ys) / len(ys)
    a *= 0.5
    return abs(a), cx / (6 * a), cy / (6 * a)


def sql(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    with open(SRC, encoding="utf-8") as fh:
        data = json.load(fh)

    states = {}            # name -> code
    districts = defaultdict(list)   # (state, district) -> list of rings (outer rings only)
    edge_owner = defaultdict(list)  # edge key -> list of state names

    for f in data["features"]:
        p = f["properties"]
        st = p["st_nm"].strip()
        dt = (p.get("district") or "").strip() or "~"  # "~" = unnamed fragment: drawn, never seeded
        states.setdefault(st, p.get("st_code", ""))
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            for k, ring in enumerate(poly):
                if k == 0:
                    districts[(st, dt)].append(ring)
                for a, b in zip(ring, ring[1:]):
                    ka, kb = q(a), q(b)
                    if ka == kb:
                        continue
                    edge_owner[tuple(sorted([ka, kb]))].append(st)

    # ---- state boundary segments -> polylines
    seg = [e for e, owners in edge_owner.items() if len(owners) == 1 or len(set(owners)) > 1]
    adj = defaultdict(list)
    for a, b in seg:
        adj[a].append(b)
        adj[b].append(a)
    used = set()
    lines = []
    for a, b in seg:
        if (a, b) in used:
            continue
        used.add((a, b)); used.add((b, a))
        line = [a, b]
        # extend forward
        while True:
            last = line[-1]
            nxt = [n for n in adj[last] if (last, n) not in used]
            if len(adj[last]) != 2 or not nxt:
                break
            n = nxt[0]
            used.add((last, n)); used.add((n, last))
            line.append(n)
        # extend backward
        while True:
            first = line[0]
            nxt = [n for n in adj[first] if (first, n) not in used]
            if len(adj[first]) != 2 or not nxt:
                break
            n = nxt[0]
            used.add((first, n)); used.add((n, first))
            line.insert(0, n)
        lines.append(line)

    state_names = sorted(states)
    sidx = {s: i for i, s in enumerate(state_names)}
    dkeys = sorted(districts)
    named = [k for k in dkeys if k[1] != "~"]

    os.makedirs(os.path.dirname(MAP_OUT), exist_ok=True)
    with open(MAP_OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("SCMSMAP 1\n")
        out.write(f"STATES {len(state_names)}\n")
        for s in state_names:
            out.write(f"S {sidx[s]} {s}\n")
        out.write(f"DISTRICTS {len(dkeys)}\n")
        for st, dt in dkeys:
            rings = districts[(st, dt)]
            out.write(f"D {sidx[st]} {len(rings)} {dt}\n")
            for ring in rings:
                pts = ring[:-1] if ring[0] == ring[-1] else ring
                out.write(f"R {len(pts)} " + " ".join(f"{x:.4f} {y:.4f}" for x, y in pts) + "\n")
        out.write(f"BORDERS {len(lines)}\n")
        for line in lines:
            out.write(f"B {len(line)} " + " ".join(f"{x:.4f} {y:.4f}" for x, y in line) + "\n")
        out.write("END\n")

    # ---- SQL seed for geography
    with open(SQL_OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- GENERATED by tools/convert_geojson.py from tools/india_districts.geojson. Do not edit by hand.\n")
        out.write("-- States, districts and one district-headquarters city per district (centroid coordinates).\n\n")
        out.write("INSERT INTO states (name, code) VALUES\n")
        out.write(",\n".join(f"  ({sql(s)}, {sql(states[s] or str(sidx[s]))})" for s in state_names) + ";\n\n")
        out.write("INSERT INTO districts (state_id, name) VALUES\n")
        out.write(",\n".join(f"  ((SELECT id FROM states WHERE name = {sql(st)}), {sql(dt)})" for st, dt in named) + ";\n\n")
        rows = []
        for st, dt in named:
            best = max((ring_area_centroid(r) for r in districts[(st, dt)]), key=lambda t: t[0])
            _, lon, lat = best
            rows.append(
                f"  ((SELECT d.id FROM districts d JOIN states s ON s.id = d.state_id "
                f"WHERE s.name = {sql(st)} AND d.name = {sql(dt)}), {sql(dt)}, {lat:.5f}, {lon:.5f})"
            )
        out.write("INSERT INTO cities (district_id, name, latitude, longitude) VALUES\n")
        out.write(",\n".join(rows) + ";\n")

    pts = sum(len(r) for k in dkeys for r in districts[k])
    print(f"states={len(state_names)} districts={len(named)} map_parts={len(dkeys)} ring_points={pts} border_lines={len(lines)}")
    print("wrote", MAP_OUT)
    print("wrote", SQL_OUT)


if __name__ == "__main__":
    main()
